/*char a[10000];
含义：声明（定义）了一个变量。
char：表示这个变量是用来存放字符的。
a：变量的名字。
[10000]：表示这是一个数组，里面可以存放最多 10000 个字符。
作用：这就好比准备了一个能装 10000 个字的“大盒子”，用来接收用户输入的字符串。
 gets(a);针对于scanf的替代
含义：调用 gets 函数进行输入。
作用：程序运行到这里会暂停，等待你在键盘上打字并按回车。它会把这一整行文字（包括空格）都存进刚才定义的数组 a 里。
注意：这里不需要加 & 符号，因为数组名 a 本身就代表了这块内存的首地址。
puts(a);
含义：调用 puts 函数进行输出。
作用：把数组 a 里存的内容打印到屏幕上，并且自动换行。
对比：如果你用 printf("%s", a); 效果类似，但 printf 不会自动换行，需要手动加 \n。*/