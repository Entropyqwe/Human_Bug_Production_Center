//*关于基本数据类型
/*基本数据类型关键字总结

在经典编程语言（如 C、C++、Java 等）中，基本数据类型关键字用于声明存储不同数值或字符的变量。以下是按类别划分的核心基本数据类型关键字：

1. 整数类型 (Integer Types)

用于表示不带小数点的整数（分为有符号与无符号）。

int：标准整数类型（最常用）。

short：短整型，占用内存比 int 小。

long：长整型，表示范围比 int 更大。

long long：（C99/C++）超长整型，用于处理极大整数。

signed：声明有符号数值（通常可省略，默认有符号）。

unsigned：声明无符号数值（仅能表示非负数，正数范围翻倍）。

2. 浮点类型 (Floating-Point Types)

用于表示带小数点的实数。

float：单精度浮点型，占用内存较小，精度较低。

double：双精度浮点型，精度和范围高于 float（最常用）。

3. 字符与文本类型 (Character Types)

用于表示单个字符或编码。

char：基础字符型，存储单个 ASCII 字符或小整数。

wchar_t：（C/C++）宽字符型，用于存储多字节/Unicode 字符。

4. 布尔类型 (Boolean Types)

用于表示逻辑真假（true / false）。

bool：（C++/Java/现代 C）布尔型关键字。

_Bool：（C99 标准原生的布尔关键字，通常通过 <stdbool.h> 别名为 bool）。

5. 空类型 (Void Type)

void：无类型/空类型。常用于函数无返回值声明、无参数列表或泛型指针（如 void*）。

不同语言特有的补充说明：

Java 增加了 byte（1字节有符号整数），且不支持 unsigned、signed 和 long long 关键字。

C# 在上述基础上直接支持如 sbyte、uint、ulong、ushort 以及精度极高的 decimal 关键字。*/
