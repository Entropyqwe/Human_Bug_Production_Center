//*数列类问题求解时，设置三个变量，用来存储当前数列的值、前一个数列的值和前两个数列的值。通过迭代计算每个数列的值，直到达到所需的项数。
//*不断地更新变量值，直到计算出所需的数列项。最后输出结果。
#include <stdio.h>
//设置三个变量进行数列存储
int main() {
    int n;
    int a=1;
    int b=1;
    int c;
    scanf("%d",&n);
    if(n<=2){
        printf("1\n");
        return 0;
    }
    for(int i=3;i<=n;i++){
        c=a+b;
        a=b;
        b=c;//赋值必须讲究顺序，如果先赋值b会导致b的值被覆盖，导致后来的a赋值出现错误
    }
    printf("%d",c);
    return 0;
}