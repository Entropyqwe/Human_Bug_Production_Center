//*题目引入：细胞计数
/*题目描述
在一个 n × m 的显微镜视野中，1 代表细胞，0 代表背景。
如果一个细胞的上下左右四个方向（注意：这里只考虑 4 个方向）中，只要有一个也是细胞，我们就认为这个细胞是"活跃"的。

请你输出一个新的矩阵：

如果原位置是 0，输出 0。
如果原位置是 1，且它周围（上下左右）至少有一个 1，输出 2（代表活跃）。
如果原位置是 1，但周围全是 0，输出 1（代表孤立）。
输入描述
第一行输入两个整数 n, m（1 ≤ n, m ≤ 100）。
接下来 n 行，每行 m 个数字（0 或 1），中间无空格。

输出描述
输出 n 行 m 列的矩阵，表示判定后的结果*/
//*定义两个数组dx[4]和dy[4]通过for循环进行遍历
//*必须要判断两个数组在不在范围内（map[nx][ny]在不在[0,n]和[0,m]范围内，否则会越界
//*只需要判断出一个邻居即可以判定为活跃
#include <stdio.h>

#define MAX_N 105
#define MAX_M 105

char map[MAX_N][MAX_M]; // 存储输入的 0/1 矩阵

// 【核心】方向数组：上、下、左、右
int dx[] = {-1, 1, 0, 0};//横
int dy[] = {0, 0, -1, 1};//纵

int main(void) {
    int n, m;
    
    // 1. 读取矩阵尺寸
    if (scanf("%d %d", &n, &m) != 2) {
        return 1; // 输入错误，返回非0
    }

    // 2. 读取矩阵内容
    for (int i = 0; i < n; i++) {
        scanf("%s", map[i]);//*会自动地填入数组，并且填入的数组如果是0，会自动将这一整个都转化为字符串吗方便后续调用
    }

    // 3. 遍历每一个格子
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < m; j++) {
            
            // 情况 A：背景，直接输出 0
            if (map[i][j] == '0') {
                printf("0");
            } 
            // 情况 B：细胞，检查周围
            else {
                int is_active = 0; // 标记：0=孤立，1=活跃

                // 遍历 4 个方向
                for (int k = 0; k < 4; k++) {
                    int nx = i + dx[k]; // 邻居的行
                    int ny = j + dy[k]; // 邻居的列

                    // 【关键】边界检查：确保不越界
                    if (nx >= 0 && nx < n && ny >= 0 && ny < m) {
                        if (map[nx][ny] == '1') {
                            is_active = 1; // 发现邻居，标记为活跃
                            break;         // 只要有一个就够了，立刻停止查找
                        }
                    }
                }

                // 根据标记输出结果
                if (is_active) {
                    printf("2"); // 活跃细胞
                } else {
                    printf("1"); // 孤立细胞
                }
            }
        }
        printf("\n"); // 每行结束换行
    }

    return 0;
}
