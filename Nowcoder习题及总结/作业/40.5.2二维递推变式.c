// 1. 题目描述
// 在一个n*M的网格迷宫中，一个机器人位于左上角 (1, 1)，它的目标是前往右下角 (n, m) 寻找宝藏。
// 机器人每次只能向右或向下移动一步。
// 网格中某些格子存在障碍物，机器人无法进入。我们用二维数组 `grid` 表示迷宫：
// - `grid[i][j] = 0` 表示该格子是空地，可以通行；
// - `grid[i][j] = 1` 表示该格子有障碍物，不可通行

// 请计算机器人从左上角走到右下角，总共有多少条不同的合法路径？
// 由于路径数量可能非常庞大，请将最终结果对 $1,000,000,007$ 取模后输出。

#include<stdio.h>
//此类题先画图，再遍历
#define MOD 1000000007LL // 错因标注：题目要求的是 1,000,000,007，原来少写了一个 0。
int grid[1005][1005]={0};
long long dp[1005][1005]={0};
int main(void){
//先考虑防御
    int n,m;
    printf("请输入两个数字：");
    if(scanf("%d %d",&n,&m)!=2){
        return 1;
    }

//画图
    int i,j;
    for(i=1;i<=n;i++){
        // 错因标注：原代码写成 m++，没有递增 j，会一直停在同一列，造成死循环。
        for(j=1;j<=m;j++){
            scanf("%d",&grid[i][j]);
        }
    }
    // 错因标注：输入下标从 1 开始，起点是 grid[1][1]，不是 grid[0][0]。
    if (grid[1][1] == 1) {
        printf("0\n"); // 起点被堵死，无路径
        return 0;
    }
    dp[1][1] = 1;
//下面开始遍历矩阵
    for(i=1;i<=n;i++){
        for(j=1;j<=m;j++){
            if(i==1 && j==1) continue;
            // 错因标注：0 表示可通行，1 表示障碍；原代码把条件写反了。
            if(grid[i][j]==1){
                dp[i][j]=0;
            }else{
                // 错因标注：列循环上界应为 m，原代码写成 n，n!=m 时会漏算或越界。
                dp[i][j]=(dp[i-1][j]+dp[i][j-1])%MOD;
            }
        }
    }
    printf("%lld\n", dp[n][m]);
    return 0;
}
// 样例输入
// 3 3
// 0 0 0
// 0 1 0
// 0 0 0
//  5. 样例输出
// 2