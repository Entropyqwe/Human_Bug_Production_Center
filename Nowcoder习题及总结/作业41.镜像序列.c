#include <stdio.h>

int main() {
    int n;
    int a[105]; // 题目提示 n <= 100，定义一个稍大的数组防止溢出
    int count = 0; // 用于记录实际存储了多少个有效数字

    // 1. 循环读取输入，直到遇到 0 或者数组满了
    // scanf 会返回成功读取的变量个数，这里用来确保读取成功
    while (scanf("%d", &n) == 1 && n != 0) {
        a[count] = n; // 将数字存入数组
        count++;      // 计数器加 1
    }

    // 2. 倒序输出
    // 从 count-1 (最后一个存入的下标) 开始，递减到 0
    for (int i = count - 1; i >= 0; i--) {
        printf("%d", a[i]);

        // 3. 控制空格格式
        // 只要不是最后一个输出的数字（即下标不为0），就在后面打印空格
        if (i > 0) {
            printf(" ");
        }
    }

    // 很多在线判题系统要求最后有一个换行符
    printf("\n");

    return 0;
}
