//*goto语句的使用
/*goto语句可以让程序直接跳转到指定的标签处执行代码，标签是一个标识符，后面跟着一个冒号。使用goto语句可以实现一些特殊的控制流程，比如跳出多层循环或者实现状态机等。但是，过度
使用goto语句会导致代码难以理解和维护，因此在现代编程中，建议尽量避免使用goto语句，而是使用更结构化的控制流语句，如循环和函数调用等。*/