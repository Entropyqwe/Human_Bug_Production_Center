//猜数游戏如何描述
//1. 生成一个随机数
//2. 提示用户输入猜测的数
//3. 判断用户输入的数与随机数的大小关系
//4. 根据判断结果给出提示
//5. 重复步骤2-4直到用户猜中为止，如何设置循环（输出值与既定值相等）
#include <stdio.h>
#include <stdlib.h>//*引入随机数函数库，rand()函数用于生成随机数，srand()函数用于设置随机数种子，二者均在这个库中
#include <time.h>//*引入时间函数库，time()函数用于获取当前时间，作为随机数种子
int main()
{
    srand(time(0));//*设置随机数种子，以获取一个自1970开始的随机数，即伪随机
    int a =rand();

    printf("%d\n",a);

    return 0;
}
