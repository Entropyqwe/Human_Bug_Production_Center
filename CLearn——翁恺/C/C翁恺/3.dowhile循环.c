//*引入：如何比较任意位数，取余的思想
//*关键思想：取余与整除，例如a/=10，即下一步的a值为上一步的a值除以10后的结果（用于循环定义）
#include<stdio.h>
    int main()
{
    int x;
    int n=0;//*输入的是n=0是为了避免输入0时导致系统输出为0位数

    printf("请输入数字");
    scanf("%d",&x);
    do{//在do while循环之间为循环体，它必然进行一次，在执行后再判断条件是否成立，若成立则继续执行循环体，若不成立则结束循环
        n++;
        x/=10;
    }while(x>0);
    printf("该数字是%d位数\n",n);
    return 0;

    }