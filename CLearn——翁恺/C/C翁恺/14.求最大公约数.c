//*辗转相除法
#include <stdio.h>
int main()
{
    int a, b, r;
    printf("请输入两个正整数：");
    scanf("%d %d", &a, &b);
    //*欧几里得算法的核心在于退=推导出余数和其中任何一个数的最大公约数和这两个数的最大公约数相同
    while(b != 0)
    {
        r = a % b;//r是a和b两个数的余数
        a = b;
        b = r;
    }
    printf("最大公约数是：%d\n", a);
    return 0;
}
