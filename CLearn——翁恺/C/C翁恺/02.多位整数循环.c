//*引入：如何比较任意位数，取余的思想
//*关键思想：取余与整除，例如a/=10，即下一步的a值为上一步的a值除以10后的结果（用于循环定义）
#include<stdio.h>
    int main()
{
    int x;
    int n=0;//*输入的是n=0是为了避免输入0时导致系统输出为0位数

    printf("请输入数字");
    scanf("%d",&x);
    n++;
    x/=10;
    while(x>0){
        n++;
        x/=10;//加入printf来验证每一轮的x值，此为检验法
    }
    printf("该数字是%d位数\n",n);
    return 0;

    }