//情景导入：判断一个数字是几位数
//通过范围来界定是几位数（例如：352在100到999区间，所以这是三位数）
//该程序限定在四位数以内的位数判断 
#include<stdio.h>
    int main(){
        int x;
        int n=1;//因为此处做的是位数的判断，假设输入的是0，那么结果为一位数。以一位数作为起点进行判定
        scanf("%d",&x);

        if (x>999){
            n=4;
        }else if (x>99){
            n=3;
        }else if (x>9){
            n=2;
        }
        
        printf("该数字是%d位数\n",n);    
    }
//*用大于的角度进行比较，必须从高到低进行